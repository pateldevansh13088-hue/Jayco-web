#!/usr/bin/env node
/* Build script: turns the data files + modules into plain HTML pages.
 *
 *   node tools/build.js
 *
 * No npm packages needed. It
 *   1. loads data/*.js and assets/js/** in a sandbox,
 *   2. writes every page listed in assets/js/pages.js as a static .html file,
 *   3. writes sitemap.xml and robots.txt,
 *   4. joins all scripts into assets/js/site.bundle.js (the only script pages load).
 * Re-run it after you edit anything in data/ or assets/js/.
 */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

const ORDER = [
  "data/site.js", "data/categories.js", "data/brands.js", "data/products.js", "data/services.js", "data/content.js",
  "assets/js/core/icons.js", "assets/js/core/util.js", "assets/js/core/art.js", "assets/js/core/store.js", "assets/js/core/search.js",
  "assets/js/modules/layout.js", "assets/js/modules/products.js", "assets/js/modules/categories.js", "assets/js/modules/brands.js",
  "assets/js/modules/services.js", "assets/js/modules/testimonials.js", "assets/js/modules/faq.js", "assets/js/modules/articles.js",
  "assets/js/modules/about.js", "assets/js/modules/maps.js", "assets/js/modules/contact.js", "assets/js/modules/home.js",
  "assets/js/pages.js"
];
const APP = "assets/js/app.js";

/* ---------- 1. load everything in a sandbox that looks like a browser window ---------- */
const sandbox = { console, Date, Math, JSON, Intl, Object, Array, String, Number, RegExp, Error, Set, Map };
sandbox.window = sandbox;
vm.createContext(sandbox);
ORDER.forEach((f) => vm.runInContext(read(f), sandbox, { filename: f }));
const J = sandbox.JAICO;

/* ---------- 2. write the pages ---------- */
function clean() {
  ["products", "category", "brand", "guides", "subject", "health-articles"].forEach((d) => fs.rmSync(path.join(ROOT, d), { recursive: true, force: true }));
  ["medicines.html", "healthcare.html", "health-articles.html"].forEach((f) => fs.rmSync(path.join(ROOT, f), { force: true }));
}
clean();

const defs = J.pages.list();
const seenPaths = new Set();
defs.forEach((def) => {
  if (seenPaths.has(def.path)) throw new Error("Duplicate page path: " + def.path);
  seenPaths.add(def.path);
  const html = J.pages.html(def);
  const out = path.join(ROOT, def.path);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
});

/* ---------- 3. sitemap + robots ---------- */
const today = new Date().toISOString().slice(0, 10);
J.ctx.root = "";
const base = J.data.site.baseUrl.replace(/\/$/, "");
const urls = defs.filter((d) => d.sitemap !== false).map((d) => {
  const loc = d.path === "index.html" ? base + "/" : base + "/" + d.path;
  const pri = d.path === "index.html" ? "1.0" : /^(products|category|brand|health-articles)\//.test(d.path) ? "0.6" : "0.8";
  return `  <url><loc>${loc}</loc><lastmod>${today}</lastmod><priority>${pri}</priority></url>`;
});
fs.writeFileSync(path.join(ROOT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`);
fs.writeFileSync(path.join(ROOT, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${base}/sitemap.xml\n`);

/* ---------- 4. bundle for the browser ---------- */
const banner = "/* Generated by tools/build.js. Edit the files in data/ and assets/js/, then run the build again. */\n";
const bundle = banner + ORDER.concat([APP]).map((f) => `/* ---- ${f} ---- */\n${read(f)}`).join("\n");
fs.writeFileSync(path.join(ROOT, "assets/js/site.bundle.js"), bundle);

console.log(`Built ${defs.length} pages, sitemap.xml, robots.txt and site.bundle.js (${Math.round(bundle.length / 1024)} KB).`);
